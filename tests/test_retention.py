"""Tests for drawer retention: the magnet-pair holes (drawer Back wall <->
divider) and the magnet press-fit coupon.  The turn-button lid lock was
removed on 2026-10-10 (Ben's decision, red-team G25): the lid is held by
friction only, so there is no button part, no front-wall pivot hole and no
bolt, and the tests below guard that nothing of it comes back.

Style follows test_svg_geometry.py: parse the real SVGs with
tests/svg_utils.py, existence-first, literal bounds -- and, for the
positional checks, an independent-datum cross-check (compute the expected
position from a DIFFERENT config constant / a different generated file than
whatever the generator itself used, so the test can't just be checking that
the generator agrees with itself).
"""

