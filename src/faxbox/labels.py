ADVANCE = 6.0      # units per character (4 wide + 2 gap)


def text_width(text: str, height: float) -> float:
    n = len(text)
    return (n * ADVANCE - 2.0) * height / 6.0 if n else 0.0


def stroke_text(text: str, height: float) -> list[list[tuple[float, float]]]:
    """Polylines (mm, y up, origin bottom-left) for `text` (upper-cased)."""
    k = height / 6.0
    out = []
    x = 0.0
    for ch in text.upper():
        for line in _G.get(ch, []):
            out.append([(x + px * k, py * k) for px, py in line])
        x += ADVANCE * k
    return out
