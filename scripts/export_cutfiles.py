"""Generate the downloadable cut-file sets for every stock thickness (2.8 ... 3.5 mm)
and every laser kerf.

    python scripts/export_cutfiles.py [--out site/downloads] [--only 3.2 3.3] [--keep-folders]

For each thickness T this runs `python -m faxbox.cutset` in its own process with
FAXBOX_THICKNESS=T (the geometry reads T at import time) for the kerfs in
faxbox.cutset.KERFS, then packs the result into zips (the loose files are removed
afterwards; only the small coupon files stay loose):

    fax-machine-box_T<T>_k<kerf>_cut.zip                   cut only, all beds, plus coupon files
    fax-machine-box_T<T>_k<kerf>_labels.zip                cut + labels (inside face up)
    fax-machine-box_T<T>_k<kerf>_engrave_<bed>.zip         cut + engrave, one per bed
    fax-machine-box_T<T>_parts.zip                         zero-kerf single parts + art parts (faces/)
    coupon/T<T>_coupon.svg|dxf, T<T>_coupon_marked.svg|dxf  the test-fit coupon
    manifest.json, README.md                               schema 3, see README.md

Everything is deterministic.
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
import zipfile
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
THICKNESSES = [round(2.8 + 0.1 * i, 1) for i in range(8)]

README_TEMPLATE = """# Cut-file downloads (manifest schema 3)

Generated by `scripts/export_cutfiles.py`. Only `manifest.json`, `README.md` and `.gitignore`
are committed; the zips and the coupon files are built.

## Files

For every thickness T (2.8 ... 3.5 mm, 0.1 steps) and laser kerf (diode 0.12, CO2 0.18, Ponoko 0.20 mm):

| file | contents |
| --- | --- |
| `fax-machine-box_T<T>_k<kerf>_cut.zip` | cut-only SVG + DXF sheets, one set per bed, plus the coupon files. Blue lines only, so a service that cuts every line cuts exactly the parts |
| `fax-machine-box_T<T>_k<kerf>_labels.zip` | cut + labels for your own laser: parts lie inside face up, gray part letters and joint numbers (layer LABELS), red faceplate glue-up lines |
| `fax-machine-box_T<T>_k<kerf>_engrave_<bed>.zip` | cut + engrave for one bed: art on the outside of the parts that carry it (mirrored outlines where needed), gray joint labels on the inside of the rest |
| `fax-machine-box_T<T>_parts.zip` | zero-kerf single-part files (service applies its own kerf) and `faces/`: the 11 art parts, 15 variants |
| `coupon/T<T>_coupon[_marked].svg\\|dxf` | the test-fit coupon, loose (also inside every cut zip) |

Every zip has a `README.txt`. SVG: 1 unit = 1 mm. DXF: R2000, millimetres, layers CUT / ENGRAVE / LABELS.
The art is filled shapes: in a DXF set layer ENGRAVE to fill / raster.

## manifest.json

```
schema: 3
kerfs:    id -> {kerf_mm, label}                      diode / co2 / ponoko
versions: cut_only | cut_labels | cut_engrave -> {label, text}
beds:     bed -> {label, width_mm, height_mm, margin_mm, spacing_mm, stock{name,width_mm,height_mm},
                  note, kerfs[], engrave_kerfs[]}
          bed ids: ponoko, xtool_s1, xtool_p2 (also the 12 x 24 in stock layout), glowforge_pro,
          generic_600x400, nycr_32x20.  stock = the sheet size a layout needs.
parts_list: [{letter, name, qty, plate}]
engrave:  colors, dxf_layers, dxf_note, conventions[], default_variants{face: variant},
          faces{face: {title, part_id, flipped, exterior_face, variants[{id,label,default,notes,ink_pct}]}}
coupon_guide: {order[], features[]}   structured reading guide for the coupon (features have ids,
          drawn sizes, formulas and what to do with each reading)
thicknesses: "3.2" -> {
    wall_id: {left_divider_holes, right_divider_holes, rule}   hole counts depend on T; the left wall
                                                                always has one more
    coupon: {svg, dxf, svg_marked, dxf_marked, layout[{part,x_mm,y_mm,width_mm,height_mm,rotated}]}
    parts: {zip, parts[{letter,name,qty,stem}], min_clearance_mm{face/variant: mm}}
    joint_map: {joints[{id, parts[{part,name,plate,edge,x_mm,y_mm}, ...]}],
                labelled_on_inside_face{part letter: [joint ids]}, art_parts_unlabelled[], note}
    kerfs: "0.18" -> {
        id, kerf_mm,
        cut_only:    {zip, sheets{bed: n}}
        cut_labels:  {zip, sheets{bed: n}}
        cut_engrave: {beds{bed: {zip, sheets}}}              only beds listed in engrave_kerfs
    }
}
```

Paths are relative to this folder. `x_mm, y_mm` in the joint map are in the part's own zero-kerf frame
(origin bottom-left of the nominal rectangle, y up, outline as drawn).
"""


def _zip(path: Path, root: Path, names: list[str], top: str, extra: dict[str, bytes] | None = None) -> None:
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for name in sorted(names):
            zi = zipfile.ZipInfo(f"{top}/{name}", (2026, 1, 1, 0, 0, 0))
            zi.compress_type = zipfile.ZIP_DEFLATED
            zi.external_attr = 0o644 << 16
            z.writestr(zi, (root / name).read_bytes(), compresslevel=9)
        for name, data in sorted((extra or {}).items()):
            zi = zipfile.ZipInfo(f"{top}/{name}", (2026, 1, 1, 0, 0, 0))
            zi.compress_type = zipfile.ZIP_DEFLATED
            zi.external_attr = 0o644 << 16
            z.writestr(zi, data, compresslevel=9)


def build_one(t: float, out: Path, kerfs: list[float], keep: bool) -> dict:
    work = out / f"_build_T{t:.1f}"
    if work.exists():
        shutil.rmtree(work)
    env = dict(os.environ, FAXBOX_THICKNESS=str(t), PYTHONPATH=str(SRC))
    subprocess.run([sys.executable, "-m", "faxbox.cutset", str(work), *[f"{k:.2f}" for k in kerfs]],
                   check=True, env=env, capture_output=True)
    sys.path.insert(0, str(SRC))
    base = f"fax-machine-box_T{t:.1f}"
    entry = {"kerfs": {}}
    common = json.loads((work / "set.json").read_text())
    coupon_dir = out / "coupon"
    coupon_dir.mkdir(exist_ok=True)
    first = None
    for k in kerfs:
        folder = work / f"k{k:.2f}"
        info = json.loads((folder / "set.json").read_text())
        top = f"{base}_k{k:.2f}"
        cut_files = list(info["files"]) + ["README.txt"]
        _zip(out / f"{top}_cut.zip", folder, cut_files, top)
        lab = [f for f in info["label_files"] if not f.endswith("README.txt")] + ["labels/README.txt"]
        _zip(out / f"{top}_labels.zip", folder, lab, top, {"coupon_marked.svg": (folder / "coupon_marked.svg").read_bytes(),
                                                           "coupon_marked.dxf": (folder / "coupon_marked.dxf").read_bytes()})
        kid = info["kerf_id"]
        bed_entries = {}
        for bed, files in info["engrave_files"].items():
            if not files:
                continue
            name = f"{top}_engrave_{bed}.zip"
            _zip(out / name, folder, files + ["README_engrave.txt"], top)
            bed_entries[bed] = {"zip": name, "sheets": info["beds"][bed]["sheets"]}
        sheets = {b: v["sheets"] for b, v in info["beds"].items()}
        entry["kerfs"][f"{k:.2f}"] = {
            "id": kid, "kerf_mm": k,
            "cut_only": {"zip": f"{top}_cut.zip", "sheets": sheets},
            "cut_labels": {"zip": f"{top}_labels.zip", "sheets": sheets},
            "cut_engrave": {"beds": bed_entries},
        }
        if first is None:
            first = info
            for ext in ("svg", "dxf"):
                for stem, key in (("coupon", ext), ("coupon_marked", f"{ext}_marked")):
                    shutil.copy(folder / f"{stem}.{ext}", coupon_dir / f"T{t:.1f}_{stem}.{ext}")
        else:   # the coupon does not depend on the kerf of the set
            assert (folder / "coupon.svg").read_bytes() == (work / f"k{kerfs[0]:.2f}" / "coupon.svg").read_bytes()
    parts_dir = work / "parts"
    pinfo = common["parts"]
    _zip(out / f"{base}_parts.zip", parts_dir, pinfo["files"], f"{base}_parts")
    entry["wall_id"] = first["wall_id"]
    entry["joint_map"] = first["joint_map"]
    entry["coupon"] = {"svg": f"coupon/T{t:.1f}_coupon.svg", "dxf": f"coupon/T{t:.1f}_coupon.dxf",
                       "svg_marked": f"coupon/T{t:.1f}_coupon_marked.svg",
                       "dxf_marked": f"coupon/T{t:.1f}_coupon_marked.dxf", "layout": first["coupon_layout"]}
    entry["parts"] = {"zip": f"{base}_parts.zip", "parts": pinfo["parts"], "min_clearance_mm": pinfo["min_clearance_mm"]}
    entry["_guide"] = first["coupon_guide"]
    entry["_default_variants"] = first["engrave"]["default_variants"]
    if not keep:
        shutil.rmtree(work)
    return entry


def engrave_block(eg) -> dict:
    faces = {}
    for f in eg.faces():
        m = eg.art_manifest()[f]
        faces[f] = {"title": m["title"], "part_id": m["part_id"], "flipped": bool(m["engrave_part_flipped"]),
                    "exterior_face": m["exterior_face"],
                    "variants": [{"id": v["id"], "label": v["label"], "default": bool(v.get("default")),
                                  "notes": v.get("notes", ""), "ink_pct": v.get("ink_pct")}
                                 for v in m["variants"]]}
    return {
        "colors": {"cut": "#0000FF", "engrave_fill": "#000000", "engrave_line": "#FF0000", "labels": "#808080"},
        "dxf_layers": {"cut": "CUT", "engrave": "ENGRAVE", "labels": "LABELS"},
        "dxf_note": "DXF has no fill attribute: the engraved art is closed polylines on layer ENGRAVE, "
                    "so set that layer to fill / raster in the laser software.",
        "conventions": [
            "Cuts are kerf-offset; engraving is not.",
            "Engraving stays at least 0.35 mm from every cut.",
            "Parts with art lie outside face up. Parts flagged 'flipped' are mirrored in the cut + engrave "
            "files for this; the art is not mirrored. Never flip a part to engrave a second side.",
            "Parts without art lie inside face up and carry gray joint labels: the same number on the two "
            "edges that meet.",
            "The drawer faceplate glue-up lines are in the cut + labels files only.",
        ],
        "default_variants": {f: eg.default_variant(f) for f in eg.faces()},
        "faces": faces,
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "site" / "downloads"))
    ap.add_argument("--only", nargs="*", type=float)
    ap.add_argument("--keep-folders", action="store_true")
    a = ap.parse_args()
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    sys.path.insert(0, str(SRC))
    from faxbox import assembly3d as A
    from faxbox import engrave as eg
    from faxbox.cutset import BED_INFO, BEDS, HOBBY_AND_SERVICE_BEDS, KERF_LABELS, KERFS, README_KINDS
    kerfs = list(KERFS.values())
    ts = [t for t in THICKNESSES if not a.only or t in a.only]
    for old in list(out.glob("fax-machine-box_T*.zip")):
        if not a.only or any(f"_T{t:.1f}_" in old.name for t in ts):
            old.unlink()
    with ThreadPoolExecutor(max_workers=4) as ex:
        entries = list(ex.map(lambda t: build_one(t, out, kerfs, a.keep_folders), ts))

    manifest = {
        "schema": 3,
        "kerfs": {k: {"kerf_mm": v, "label": KERF_LABELS[k]} for k, v in KERFS.items()},
        "versions": {
            "cut_only": {"label": "Cut only", "text": README_KINDS["cut"].strip().splitlines()[1]},
            "cut_labels": {"label": "Cut + labels", "text": "For your own laser: gray part letters and joint numbers on the inside face."},
            "cut_engrave": {"label": "Cut + engrave", "text": "Art on the outside of the art parts; joint labels inside the rest."},
        },
        "beds": {},
        "parts_list": [{"letter": l, "name": n, "qty": q, "plate": p} for l, p, n, q in A.INVENTORY],
        "engrave": engrave_block(eg),
        "thicknesses": {},
    }
    for bed in HOBBY_AND_SERVICE_BEDS:
        w, h, margin, spacing = BEDS[bed]
        i = BED_INFO[bed]
        manifest["beds"][bed] = {"label": i["label"], "width_mm": w, "height_mm": h, "margin_mm": margin,
                                 "spacing_mm": spacing, "stock": i["stock"], "note": i["note"],
                                 "kerfs": i["kerfs"], "engrave_kerfs": i["engrave_kerfs"]}
    for t, e in zip(ts, entries):
        manifest["coupon_guide"] = e.pop("_guide")
        e.pop("_default_variants")
        manifest["thicknesses"][f"{t:.1f}"] = e
    old = out / "manifest.json"
    if a.only and old.exists():                     # keep the other thicknesses of an earlier full run
        prev = json.loads(old.read_text())
        if prev.get("schema") == 3:
            prev["thicknesses"].update(manifest["thicknesses"])
            manifest["thicknesses"] = dict(sorted(prev["thicknesses"].items()))
    old.write_text(json.dumps(manifest, indent=1) + "\n")
    (out / "README.md").write_text(README_TEMPLATE)
    (out / ".gitignore").write_text("*\n!manifest.json\n!README.md\n!.gitignore\n")

    total = sum(f.stat().st_size for f in out.rglob("*") if f.is_file())
    print(f"{len(ts)} thicknesses, {total / 1024 / 1024:.1f} MB in {out}")


if __name__ == "__main__":
    main()
